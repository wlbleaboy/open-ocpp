/** @brief A tariff is described by fields with prices for:
energy,
charging time,
idle time,
fixed fee,
reservation time,
reservation fixed fee. +
Each of these fields may have (optional) conditions that specify when a price is applicable. +
The _description_ contains a human-readable explanation of the tariff to be shown to the user. +
The other fields are parameters that define the tariff. These are used by the charging station to calculate the price.
 */
struct TariffType
{
    /** @brief Unique id of tariff */
    ocpp::types::CiStringType<60u> tariffId;
    /** @brief  */
    std::vector<MessageContentType> description;
    /** @brief Currency code according to ISO 4217 */
    ocpp::types::CiStringType<3u> currency;
    /** @brief  */
    ocpp::types::Optional<TariffEnergyType> energy;
    /** @brief Time when this tariff becomes active. When absent, it is immediately active. */
    ocpp::types::Optional<ocpp::types::DateTime> validFrom;
    /** @brief  */
    ocpp::types::Optional<TariffTimeType> chargingTime;
    /** @brief  */
    ocpp::types::Optional<TariffTimeType> idleTime;
    /** @brief  */
    ocpp::types::Optional<TariffFixedType> fixedFee;
    /** @brief  */
    ocpp::types::Optional<TariffTimeType> reservationTime;
    /** @brief  */
    ocpp::types::Optional<TariffFixedType> reservationFixed;
    /** @brief  */
    ocpp::types::Optional<PriceType> minCost;
    /** @brief  */
    ocpp::types::Optional<PriceType> maxCost;
    /** @brief  */
    ocpp::types::Optional<CustomDataType> customData;
};

